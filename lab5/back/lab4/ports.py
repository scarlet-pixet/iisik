"""Command-side ports implemented by the in-process mock adapters."""
from typing import Protocol
from back.lab3.auth.models import User
from back.lab3.transaction.models import Client,Account,Transaction
from back.lab3.case.models import Case,Notification


class TransactionCommandPort(Protocol):
    def create_client(self, actor:User, input:dict) -> Client: ...
    def open_account(self, actor:User, input:dict) -> Account: ...
    def register_counterparty(self, actor:User, input:dict) -> dict: ...
    def register_transaction(self, actor:User, input:dict) -> Transaction: ...
    def transaction_summary(self, filter:dict|None=None) -> dict: ...


class CaseCommandPort(Protocol):
    def take_case(self, actor:User, caseId:str, expectedVersion:int, idempotencyKey:str) -> Case: ...
    def add_case_comment(self, actor:User, input:dict) -> Case: ...
    def escalate_case(self, actor:User, caseId:str, reason:str, expectedVersion:int, idempotencyKey:str) -> Case: ...
    def close_case(self, actor:User, input:dict) -> Case: ...
    def reopen_case(self, actor:User, caseId:str, reason:str, expectedVersion:int, idempotencyKey:str) -> Case: ...
    def mark_notification_read(self, actor:User, id:str) -> Notification: ...
