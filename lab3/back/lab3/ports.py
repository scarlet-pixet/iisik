"""Read contracts. Implementations can later be replaced with gRPC clients."""
from typing import Protocol, Any
from .auth.models import User
from .transaction.models import Client, Transaction
from .analysis.models import Profile, Result, Run, RuleVersion
from .case.models import Case, Report

class AuthReadPort(Protocol):
    def get_current_user(self) -> User: ...

class TransactionReadPort(Protocol):
    def get_client(self, id: str) -> Client | None: ...
    def get_transaction(self, id: str) -> Transaction | None: ...
    def search_clients(self, filter: dict | None = None, page: dict | None = None) -> dict: ...
    def search_transactions(self, filter: dict | None = None, page: dict | None = None) -> dict: ...

class AnalysisReadPort(Protocol):
    def get_profile(self, id: str) -> Profile | None: ...
    def get_result(self, id: str) -> Result | None: ...
    def get_run(self, id: str) -> Run | None: ...
    def list_rule_versions(self, ruleId: str) -> list[RuleVersion]: ...
    def compare_runs(self, firstId: str, secondId: str) -> dict: ...
    def get_client_activity(self, clientId: str, period: dict, currency: str, runId: str) -> dict: ...

class CaseReadPort(Protocol):
    def get_case(self, id: str) -> Case | None: ...
    def search_cases(self, filter: dict | None = None, page: dict | None = None) -> dict: ...
    def get_report(self, id: str) -> Report | None: ...
    def export_report(self, id: str) -> dict: ...
    def list_notifications(self, unreadOnly: bool | None = None, page: dict | None = None) -> dict: ...
